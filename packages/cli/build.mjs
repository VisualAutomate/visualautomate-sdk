/**
 * Building the CLI.
 *
 * One bundled file with the SDK inside it, so `npm i -g @visualautomate/cli` is
 * the only install anybody does. esbuild is a real dependency rather than a dev
 * one: `visualautomate test` and `push` compile the author's TypeScript, so the
 * bundler ships with the tool.
 *
 * The type declarations a scaffolded plugin gets are generated from the SDK's
 * own source here, at build time. That is the whole reason a plugin directory
 * needs no node_modules: the types are written into it, and they cannot drift
 * from the SDK because they are copied out of it every time this runs.
 */
import { build } from "esbuild"
import { readdir, readFile, writeFile, rm } from "node:fs/promises"

const { version } = JSON.parse(await readFile("package.json", "utf8"))

const types = await readFile("../plugin-sdk/src/types.ts", "utf8")

/*
 * The same contract as ambient declarations, for a plugin's own project.
 *
 * A repository's index.js imports nothing — the platform refuses the word — so
 * the types cannot be a module there. Stripping the exports makes every
 * interface global to the project, which is what a JSDoc "@type {PluginModule}"
 * needs to resolve.
 */
const ambient = types.replace(/^export (interface|type) /gm, "declare $1 ")

await writeFile(
    "src/ambient-declarations.ts",
    "// GENERATED by build.mjs from ../plugin-sdk/src/types.ts — do not edit.\n" +
        "// The contract as globals, written into a plugin's project by the CLI so an\n" +
        "// editor can type input, config and context. See src/repo-types.ts.\n" +
        "export const AMBIENT_DECLARATIONS = " +
        JSON.stringify(ambient) +
        "\n",
)

await writeFile(
    "src/declarations.ts",
    "// GENERATED by build.mjs from ../plugin-sdk/src/types.ts — do not edit.\n" +
        "// A scaffolded plugin imports these from ./visualautomate, which is this\n" +
        "// file's contents written into the project by `visualautomate init`.\n" +
        "export const TYPE_DECLARATIONS = " +
        JSON.stringify(types) +
        "\n",
)

/*
 * The AI skill, carried inside the binary so `vsa skill` can install it with no
 * network and no second package. The files are read from ../../skills at build
 * time, exactly as they are in the repository, so the installed skill is the
 * one this repository's tests hold to the SDK's rules.
 */
const SKILL_ROOT = "../../skills/visualautomate-steps"
const LOCAL_ONLY = new Set(["visualautomate.d.ts", "jsconfig.json", ".visualautomate", "node_modules", ".DS_Store"])
async function filesUnder(dir, prefix = "") {
    const out = {}
    for (const entry of (await readdir(dir, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
        const rel = prefix ? `${prefix}/${entry.name}` : entry.name
        // What a local run of an example leaves behind is not part of the skill.
        if (LOCAL_ONLY.has(entry.name)) continue
        if (entry.isDirectory()) Object.assign(out, await filesUnder(`${dir}/${entry.name}`, rel))
        else out[rel] = await readFile(`${dir}/${entry.name}`, "utf8")
    }
    return out
}
await writeFile(
    "src/skill-files.ts",
    "// GENERATED by build.mjs from ../../skills/visualautomate-steps — do not edit.\n" +
        "// The AI skill `vsa skill` installs, as relative path → contents. See src/ai-files.ts.\n" +
        "export const SKILL_FILES: Record<string, string> = " +
        JSON.stringify(await filesUnder(SKILL_ROOT), null, 0) +
        "\n",
)

await rm("dist", { recursive: true, force: true })

await build({
    entryPoints: ["src/index.ts"],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    outfile: "dist/index.js",
    banner: { js: "#!/usr/bin/env node" },
    // esbuild loads its own binary at run time and cannot be bundled into one
    // file; it stays a dependency and is resolved normally.
    external: ["esbuild"],
    // The SDK comes in from source rather than from node_modules, so the
    // published CLI carries exactly the SDK in this repository at the same
    // version, rather than whatever version happened to resolve.
    alias: { "@visualautomate/plugin-sdk": "../plugin-sdk/src/index.ts" },
    // `va --version`, and the sandbox image tag `--docker` asks for.
    define: { __CLI_VERSION__: JSON.stringify(version) },
})

console.log("@visualautomate/cli → dist/index.js")
